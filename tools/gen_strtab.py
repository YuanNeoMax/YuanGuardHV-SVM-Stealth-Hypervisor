#!/usr/bin/env python3
"""Generate hv/common/yghv_strtab.h -- export names as encrypted words.

WHY A GENERATOR
    YGHV_W8() takes eight characters per word, so a name is ceil(n/8) hand-typed
    lines with the index spelled out. That is a table nobody can re-check by eye,
    and a wrong index yields garbage instead of a compiler error. Generating it
    makes the contents derivable from the list in this file, so the table can be
    regenerated and diffed.

WHY THE KEY IS FIXED AND PUBLIC
    The key is not a secret and must not be treated as one: it is here and in the
    generated header, and anyone who wants the names can read the list below.
    What the encryption removes is the plaintext appearing in the BINARY, where
    "strings x.sys | grep PsGetProcess" is a real triage step. Claiming more than
    that would be the worse mistake.

DETERMINISM
    Same list plus same generator gives a byte-identical header.
    YuanGuardHV/tests/string_encryption_check.ps1 regenerates it and fails on any
    diff, so the checked-in header cannot drift from this list.
"""
import sys

NUL = chr(0)
GOLDEN = 0x9E3779B97F4A7C15
BASE_KEY = 0x5A17
NAMES = [
    "PsGetCurrentProcessId",
    "PsGetProcessId",
    "PsGetProcessImageFileName",
    "PsGetProcessPeb",
    "PsGetProcessProtection",
    "PsGetProcessSectionBaseAddress",
    "PsGetThreadId",
    "PsGetThreadProcess",
    "PsGetThreadTeb",
    "PsInitialSystemProcess",
    "PsLoadedModuleList",
    # 9.591: append-only. key_for(i) is indexed, so inserting above would
    # re-key every later name and silently change the whole table.
    "PsGetProcessInheritedFromUniqueProcessId",
    "PsGetProcessExitStatus",
]


def key_for(i):
    return (BASE_KEY + i * 0x1F3) & 0xFFFFFFFFFFFF


def raw_words(s):
    raw = s.encode("ascii") + bytes([0])
    while len(raw) % 8:
        raw += bytes([0])
    return [int.from_bytes(raw[i:i + 8], "little") for i in range(0, len(raw), 8)]


def encoded(s, key):
    return [(w ^ ((key + i * GOLDEN) & 0xFFFFFFFFFFFFFFFF)) & 0xFFFFFFFFFFFFFFFF
            for i, w in enumerate(raw_words(s))]


def ident(name):
    return "YGHV_SID_" + "".join(c if c.isalnum() else "_" for c in name.upper())


def emit():
    L = []
    a = L.append
    a("/* GENERATED by tools/gen_strtab.py -- do not edit by hand.")
    a(" *")
    a(" * Export names as encrypted words. Regenerate with:")
    a(" *     python tools/gen_strtab.py > YuanGuardHV/hv/common/yghv_strtab.h")
    a(" *")
    a(" * The key is public on purpose (see the generator); what this buys is that")
    a(" * no plaintext export name appears in the built driver, where")
    a(" * strings x.sys | grep PsGetProcess would otherwise name the capability.")
    a(" *")
    a(" * The stored words are already XORed with (key + i*GOLDEN), so decoding is")
    a(" * exactly what yghv_str_dec() does and there is no second step that could")
    a(" * disagree with it.")
    a(" */")
    a("#ifndef YGHV_STRTAB_H")
    a("#define YGHV_STRTAB_H")
    a("")
    a("#include \"yghv_str.h\"")
    a("")
    a("enum {")
    for i, n in enumerate(NAMES):
        a("    %s = %d," % (ident(n), i))
    a("    YGHV_SID_COUNT = %d" % len(NAMES))
    a("};")
    a("")
    for i, n in enumerate(NAMES):
        ws = encoded(n, key_for(i))
        a("/* %s : %d word(s), key 0x%X */" % (n, len(ws), key_for(i)))
        a("static const unsigned long long %s_w[%d] = {" % (ident(n), len(ws)))
        a("    " + ",\n    ".join("0x%016XULL" % w for w in ws))
        a("};")
        a("")
    a("static const unsigned long long *const yghv_str_words[YGHV_SID_COUNT] = {")
    for n in NAMES:
        a("    %s_w," % ident(n))
    a("};")
    a("")
    a("static const unsigned int yghv_str_nwords[YGHV_SID_COUNT] = {")
    for n in NAMES:
        a("    %d," % len(raw_words(n)))
    a("};")
    a("")
    a("static const unsigned long long yghv_str_keys[YGHV_SID_COUNT] = {")
    for i in range(len(NAMES)):
        a("    0x%XULL," % key_for(i))
    a("};")
    a("")
    a("/* Decode entry id into out (ASCII). Returns out, or 0 on a bad id. */")
    a("static __inline char *yghv_str_get(int id, char *out, unsigned int cap)")
    a("{")
    a("    if (id < 0 || id >= YGHV_SID_COUNT || !out || cap == 0) return 0;")
    a("    return yghv_str_dec(yghv_str_words[id], yghv_str_nwords[id],")
    a("                         yghv_str_keys[id], out, cap);")
    a("}")
    a("")
    a("/*")
    a(" * Wide variant, for RtlInitUnicodeString and friends. The names are ASCII,")
    a(" * so each byte widens to one WCHAR; no code page is involved.")
    a(" */")
    a("static __inline int yghv_str_get_w(int id, unsigned short *out, unsigned int cap)")
    a("{")
    a("    char narrow[YGHV_STR_MAX_CHARS];")
    a("    unsigned int i;")
    a("")
    a("    if (id < 0 || id >= YGHV_SID_COUNT || !out || cap == 0) return 0;")
    a("    if (!yghv_str_get(id, narrow, sizeof(narrow))) return 0;")
    a("    for (i = 0; i < cap - 1 && narrow[i]; i++) out[i] = (unsigned short)narrow[i];")
    a("    out[i] = 0;")
    a("    return 1;")
    a("}")
    a("")
    a("/*")
    a(" * Self-test over the GENERATED table, not over a probe: if the generator or")
    a(" * the key derivation were wrong, every name would decode to noise and this")
    a(" * is the first place that would say so.")
    a(" */")
    a("static __inline int yghv_strtab_selftest(void)")
    a("{")
    a("    char buf[YGHV_STR_MAX_CHARS];")
    a("    int i;")
    a("")
    a("    for (i = 0; i < YGHV_SID_COUNT; i++) {")
    a("        unsigned int len = 0;")
    a("        if (!yghv_str_get(i, buf, sizeof(buf))) return 0;")
    a("        while (buf[len]) len++;")
    a("        if (!len || len > YGHV_STR_MAX_CHARS - 1) return 0;")
    a("        if (buf[0] < 0x20 || buf[0] > 0x7E) return 0;")
    a("    }")
    a("    return 1;")
    a("}")
    a("")
    a("#endif /* YGHV_STRTAB_H */")
    return chr(10).join(L) + chr(10)


if __name__ == "__main__":
    sys.stdout.write(emit())
